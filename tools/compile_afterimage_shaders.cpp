#include <d3dcompiler.h>
#include <wrl/client.h>
#include <cstdio>
#include <fstream>
#include "../native/afterimage_hlsl.h"

using Microsoft::WRL::ComPtr;

int main(int argc, char** argv) {
    if (argc != 2) return 1;
    std::ofstream output(argv[1], std::ios::binary | std::ios::trunc);
    if (!output) return 1;
    output << "#pragma once\n// Generated by compile_afterimage_shaders.cpp.\nnamespace AfterimageShaders {\n";

    using namespace AfterimageHlsl;
    const struct Shader { const char* name; std::string source; const char* target; } shaders[]{
        {"Ghost", Ghost, "ps_5_0"}, {"Underlay", underlay, "ps_5_0"},
        {"GripUnderlay", gripUnderlay, "ps_5_0"},
        {"Mask", "float4 main():SV_Target{return 1;}", "ps_5_0"},
        {"Fullscreen", fullscreen, "vs_5_0"}, {"Composite", composite, "ps_5_0"},
        {"Part", part, "ps_5_0"}, {"Glove", glove, "ps_5_0"}, {"Grip", grip, "ps_5_0"}
    };
    for (const auto& shader : shaders) {
        ComPtr<ID3DBlob> code, errors;
        const HRESULT result = D3DCompile(shader.source.data(), shader.source.size(), shader.name,
            nullptr, nullptr, "main", shader.target, D3DCOMPILE_OPTIMIZATION_LEVEL3, 0,
            code.GetAddressOf(), errors.GetAddressOf());
        if (FAILED(result)) {
            std::fprintf(stderr, "Failed to compile %s: %08lx\n", shader.name, result);
            if (errors) std::fwrite(errors->GetBufferPointer(), 1, errors->GetBufferSize(), stderr);
            return 1;
        }
        output << "inline constexpr unsigned char " << shader.name << "[] = {";
        const auto* bytes = static_cast<const unsigned char*>(code->GetBufferPointer());
        for (size_t i = 0; i < code->GetBufferSize(); ++i) {
            if (i % 20 == 0) output << "\n    ";
            output << unsigned(bytes[i]) << ',';
        }
        output << "\n};\n";
    }
    output << "}\n";
    output.close();
    return output ? 0 : 1;
}
